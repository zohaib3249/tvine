// Builds the agent-readable docs from packages/tvine/AGENTS.md + docs/*.md, so they never drift:
//   llms.txt, llms-full.txt                          (repo root, committed; links point at GitHub)
//   packages/tvine/{llms.txt, llms-full.txt, docs/}  (shipped in the npm package; git-ignored)
// Guide list + one-line descriptions come from the table in docs/README.md. docs/design is internal and left out.
// Run: node scripts/build-llms.mjs (also runs from the packages/tvine build and prepack).
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'

const root = resolve(dirname(new URL(import.meta.url).pathname), '..')
const pkg = join(root, 'packages/tvine')
const GH = 'https://github.com/zohaib3249/tvine/blob/main'
const RAW = 'https://raw.githubusercontent.com/zohaib3249/tvine/main'
const read = (p) => readFileSync(join(root, p), 'utf8').trim()

// learning order: setup → data → views → pages → agents → admin → security → ops
const ORDER = ['installation', 'getting-started', 'settings-and-env', 'models-and-orm', 'views-urls-api', 'frontend-weft',
  'agents-and-mcp', 'admin', 'auth-and-security', 'shield', 'tasks-cache-email', 'testing', 'cli', 'deploy'].map((f) => `${f}.md`)
const SKIP = ['README.md', 'releasing.md']   // the index, and maintainer-only
const all = readdirSync(join(root, 'docs')).filter((f) => f.endsWith('.md'))
const guides = [...ORDER.filter((f) => all.includes(f)), ...all.filter((f) => !ORDER.includes(f) && !SKIP.includes(f)).sort()]
const rows = new Map([...read('docs/README.md').matchAll(/^\| \[([\w-]+\.md)\]\([\w-]+\.md\) \| (.+) \|$/gm)].map((m) => [m[1], m[2]]))
for (const g of guides) if (!rows.has(g)) throw new Error(`docs/README.md has no table row for ${g}`)

// Links in a docs/ file: images and ../ paths → absolute; a sibling guide stays relative only if it is in `local`
const fix = (md, local = []) => md
  .replace(/\]\(images\/([^)\s]+)\)/g, `](${RAW}/docs/images/$1)`)
  .replace(/\]\(\.\.\/([^)\s]+)\)/g, `](${GH}/$1)`)
  .replace(/\]\(([\w-]+\.md)(#[^)\s]*)?\)/g, (m, f, a = '') => local.includes(f) ? m : `](${GH}/docs/${f}${a})`)

// docs/reference/**: one topic per file, in learning order (overviews first); anything new is appended, sorted
const REF_ORDER = ['README.md', 'warp/overview.md', 'warp/models.md', 'warp/fields.md', 'warp/queryset.md', 'warp/migrations.md', 'warp/database.md',
  'warp/actions.md', 'warp/views.md', 'warp/serializers.md', 'warp/urls.md', 'warp/middleware.md', 'warp/request.md', 'warp/errors.md', 'warp/settings.md',
  'warp/contrib/auth.md', 'warp/contrib/admin.md', 'warp/contrib/tasks.md', 'warp/contrib/cache.md', 'warp/contrib/email.md', 'warp/contrib/media.md',
  'warp/contrib/audit.md', 'warp/contrib/security.md',
  'weft/overview.md', 'weft/widgets.md', 'weft/forms.md', 'weft/api-client.md', 'weft/pages-and-regions.md', 'weft/agents-in-the-browser.md']
const refAll = readdirSync(join(root, 'docs/reference'), { recursive: true }).map(String).filter((f) => f.endsWith('.md'))
const refs = [...REF_ORDER.filter((f) => refAll.includes(f)), ...refAll.filter((f) => !REF_ORDER.includes(f)).sort()]
const title = (f) => (/^# (.+)$/m.exec(read(`docs/reference/${f}`))?.[1] ?? f).replace(/`/g, '')

const full = ['# Tvine: full documentation for LLMs', '',
  'Generated by scripts/build-llms.mjs from packages/tvine/AGENTS.md and docs/*.md. Do not edit by hand.',
  'Order: the AI guide (AGENTS.md), the guides from installation to deploy, then the reference (one topic per file). Each file starts with a `# <file>` line.',
  `\n\n# packages/tvine/AGENTS.md\n\n${read('packages/tvine/AGENTS.md')}`,
  ...guides.map((f) => `\n\n# docs/${f}\n\n${fix(read(`docs/${f}`))}`),
  ...refs.map((f) => `\n\n# docs/reference/${f}\n\n${read(`docs/reference/${f}`)}`)].join('\n') + '\n'

const llms = (link, inPackage) => [
  '# Tvine', '',
  '> Tvine is an agent-native, full-stack TypeScript web framework (Warp backend: models, ORM,',
  '> migrations, auth, admin, middleware, tasks, bot protection) plus Next.js pages (Weft UI) in one process. Every backend',
  '> action is at once a typed `api.*` call, an HTTP endpoint and an MCP tool, so AI agents can read and drive the app.',
  '> npm package `tvinejs`; code imports `tvine` and the CLI runs as `tvine` (`npx tvinejs startproject mysite`, then `pnpm tvine dev`).',
  '',
  inPackage
    ? 'This file ships in the npm package: inside a project it is `node_modules/tvine/llms.txt`; the guides are in `node_modules/tvine/docs/`.'
    : 'Inside a Tvine project the same files ship in the package: `node_modules/tvine/llms-full.txt` and `node_modules/tvine/docs/<topic>.md`.',
  '',
  '## Using any Tvine site as an agent (in order)', '',
  '1. `GET /llms.txt`: what the site is and how to talk to it. Every page links it (`Link: </llms.txt>; rel="describedby"`), and so does the Shield challenge page ("Are you an AI agent?" note + `<script type="application/json" id="tvine-agent">`).',
  '2. `GET /.well-known/mcp.json` (MCP server card: endpoint, transport, tools) and `/.well-known/tvine.json` (formats, header names).',
  '3. Connect MCP at `/mcp` (Streamable HTTP) → `tools/list` → `read_page` (view "md" is the best first read) → `ui` / `do` with the control ids it shows.',
  '4. No MCP client: plain HTTP on the page URL with `Accept: text/markdown` or `x-tvine: 1`; keep the session with `x-tvine-sid` (from the first line `#tvine/1 sid=…`).',
  '5. All actions and their params: `GET /tvine/manifest`.',
  '6. Need the person\'s real logged-in browser: `request_control` → they click Allow in their tab → you drive it with a visible cursor; `release` or their Stop ends it.',
  '7. Refusals are JSON with a `hint` (`challenge_required`, `blocked`, `rate_limited`); send an honest User-Agent (`Claude-User`, `ChatGPT-User`, `Grok/1.0`). Headers reference: agents-and-mcp.md → "HTTP headers".',
  '',
  '## Start here (building a Tvine app)', '',
  `- [AGENTS.md (AI guide)](${inPackage ? 'AGENTS.md' : `${GH}/packages/tvine/AGENTS.md`}): layout, commands, recipes and rules for building a Tvine project; also written into every new project`,
  `- [Full docs in one file](${inPackage ? 'llms-full.txt' : `${GH}/llms-full.txt`}): the AI guide plus every guide below, concatenated`,
  `- [README](${GH}/README.md): what Tvine is, feature map, screenshots`,
  '',
  '## Guides', '',
  ...guides.map((f) => `- [${f}](${link(f)}): ${rows.get(f)}`),
  '',
  '## Reference (one topic per file: every option, default and example)', '',
  ...refs.map((f) => `- [${title(f)}](${inPackage ? `docs/reference/${f}` : `${GH}/docs/reference/${f}`})`),
  '',
  '## Optional', '',
  `- [Example app](${GH.replace('/blob/', '/tree/')}/examples/notes): the finished notes app from the tutorial`,
  `- [Releasing](${GH}/docs/releasing.md): publishing a new version (maintainers)`,
  ''].join('\n')

writeFileSync(join(root, 'llms-full.txt'), full)
writeFileSync(join(root, 'llms.txt'), llms((f) => `${GH}/docs/${f}`, false))
writeFileSync(join(pkg, 'llms-full.txt'), full)
writeFileSync(join(pkg, 'llms.txt'), llms((f) => `docs/${f}`, true))
rmSync(join(pkg, 'docs'), { recursive: true, force: true })
mkdirSync(join(pkg, 'docs'))
const shipped = ['README.md', ...guides]
for (const f of shipped) writeFileSync(join(pkg, 'docs', f), fix(read(`docs/${f}`), shipped) + '\n')
// the reference ships as-is (its links are relative inside docs/, which ships whole)
for (const f of refs) { mkdirSync(join(pkg, 'docs/reference', dirname(f)), { recursive: true }); writeFileSync(join(pkg, 'docs/reference', f), read(`docs/reference/${f}`)) }
console.error(`llms-full.txt: ${guides.length + 1 + refs.length} files, ${full.length} chars; packages/tvine/docs: ${guides.length + 1} guides + ${refs.length} reference files`)
