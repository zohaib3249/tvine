// Writes llms-full.txt: the AI guide (packages/tvine/AGENTS.md) + every user guide in docs/*.md, in docs/README.md order.
// docs/design is internal and left out. Run: node scripts/build-llms.mjs (or pnpm build:llms)
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
const root = resolve(dirname(new URL(import.meta.url).pathname), '..')
const all = readdirSync(join(root, 'docs')).filter((f) => f.endsWith('.md'))
const indexed = [...readFileSync(join(root, 'docs/README.md'), 'utf8').matchAll(/\]\(([\w-]+\.md)\)/g)].map((m) => m[1])
const order = [...new Set(['README.md', ...indexed, ...all.sort()])].filter((f) => all.includes(f))
const part = (path) => `\n\n<!-- ===== ${path} ===== -->\n\n${readFileSync(join(root, path), 'utf8').trim()}\n`
const out = '# Tvine: full documentation for LLMs\n\nGenerated by scripts/build-llms.mjs from packages/tvine/AGENTS.md and docs/*.md. Do not edit by hand.' +
  part('packages/tvine/AGENTS.md') + order.map((f) => part(`docs/${f}`)).join('')
writeFileSync(join(root, 'llms-full.txt'), out)
console.log(`llms-full.txt: ${order.length + 1} files, ${out.length} chars`)
